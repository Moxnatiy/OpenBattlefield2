#pragma once
// Хто вмикає змінні показу HUD.
//
// Змінна HUD у грі — це не запис у словнику, а **поле об'єкта**:
// `registerVariable` прив'язує ім'я до поля, і рушій пише саме в поле.
// Пишуть у них три різні речі, і кожна тут відтворена окремо:
//
//   * **перехід стану** — `HudObject::setState` (BF2.exe 0x786260). Два
//     switch підряд: перший за старим станом гасить те, що той показував,
//     другий за новим вмикає своє. Таблиця переходів на 32 позиції лежить
//     за 0x787008, і `tools/hud_states.py` читає її прямо з бінаря;
//   * **розмір карти** — 0x466930. Дає `MapFullSize`, `MapMinSize`,
//     `MapBorderAlternateShow` і дві складені змінні;
//   * **бойовий набір за поточним гравцем** — 0x78d0f0. Немає гравця —
//     0x78d2d9 гасить здоров'я, витривалість і значки загону. Саме через
//     це в оригіналі за екраном появи не видно смуг.
//
// Докладніше — docs/functions/hud-states.md.
#include <map>
#include <string>
#include <vector>

namespace obf2::hud {

// Словник змінних показу. Порядок тут не важить, але map дає стабільний
// обхід, а він зручний у звітах.
using VariableMap = std::map<std::string, bool>;

// Один стан і те, що він вмикає.
struct StateEntry {
  int id = 0;
  std::vector<const char*> on;
};

// Таблиця станів. Знята з BF2.exe, не переписана з рук.
const std::vector<StateEntry>& hudStates();

// Перехід у стан: спершу гасимо всі змінні, які взагалі належать станам,
// потім вмикаємо свої. У грі це роблять два switch підряд, і результат
// той самий: хвостів від попереднього екрана не лишається.
//
// Повертає true, якщо хоч щось змінилося, — тому, хто пече геометрію,
// це каже, що час перебудуватися.
bool applyState(VariableMap& variables, int state);

// Що рушій знає про світ на цей кадр.
struct WorldView {
  // Чи має гравець солдата. Не «чи під'єднаний клієнт»: у грі це
  // перевірка поточного керованого об'єкта.
  bool hasPlayer = false;
  // Карта на весь екран (екран появи) чи мініатюра в кутку.
  bool mapFullSize = false;
};

// Похідні змінні: те, що рушій рахує щокадру, а не ставить списком.
bool applyDerived(VariableMap& variables, const WorldView& view);

}  // namespace obf2::hud
